#!/usr/bin/env python3
"""Generate Rust catalog modules 1:1 from the original Owen-Launcher Kotlin sources.

Reads:
  /tmp/Owen-Launcher/app/src/main/kotlin/com/abdallhrgx/owenlauncher/core/SeasonCatalog.kt
  /tmp/Owen-Launcher/app/src/main/kotlin/com/abdallhrgx/owenlauncher/core/SeasonInfo.kt
  /tmp/Owen-Launcher/app/src/main/kotlin/com/abdallhrgx/owenlauncher/core/VersionCatalog.kt

Writes:
  crates/owen-launcher/src/core/catalogs/season_catalog.rs
  crates/owen-launcher/src/core/catalogs/version_catalog.rs
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KT = Path("/tmp/Owen-Launcher/app/src/main/kotlin/com/abdallhrgx/owenlauncher/core")
OUT = ROOT / "crates" / "owen-launcher" / "src" / "core" / "catalogs"


def split_args(text: str):
    """Split a Kotlin call's argument list on top-level commas (strings aware)."""
    args, buf, depth, in_str, esc = [], [], 0, False, False
    for ch in text:
        if esc:
            buf.append(ch); esc = False; continue
        if ch == "\\" and in_str:
            buf.append(ch); esc = True; continue
        if ch == '"':
            in_str = not in_str; buf.append(ch); continue
        if in_str:
            buf.append(ch); continue
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(buf).strip()); buf = []
            continue
        buf.append(ch)
    if buf:
        args.append("".join(buf).strip())
    return args


def extract_calls(src: str, name: str):
    """Extract every `name(...)` argument text with a quote-aware, depth-tracking scanner
    (strings may contain parentheses and commas, e.g. `(Midas, Meowscles, Skye)`)."""
    calls = []
    i = 0
    needle = name + "("
    while True:
        start = src.find(needle, i)
        if start == -1:
            break
        if start > 0 and (src[start - 1].isalnum() or src[start - 1] in "_."):
            i = start + 1
            continue
        j = start + len(needle)
        depth, in_str, esc = 1, False, False
        while j < len(src):
            ch = src[j]
            if esc:
                esc = False
            elif ch == "\\" and in_str:
                esc = True
            elif ch == '"':
                in_str = not in_str
            elif not in_str:
                if ch in "([{":
                    depth += 1
                elif ch in ")]}":
                    depth -= 1
                    if depth == 0:
                        break
            j += 1
        if j >= len(src):
            break
        calls.append(src[start + len(needle):j])
        i = j + 1
    return calls


def rs_str(kotlin_literal: str) -> str:
    """Kotlin string literal -> Rust string literal (JSON escaping is valid Rust)."""
    assert kotlin_literal.startswith('"') and kotlin_literal.endswith('"'), kotlin_literal
    return json.dumps(kotlin_literal[1:-1])


def rs_scalar(tok: str, consts: dict):
    tok = tok.strip()
    if re.fullmatch(r"-?\d+L", tok):
        return tok[:-1], "i64"
    if tok in ("true", "false"):
        return tok, "bool"
    if tok == "null":
        return "None", "opt"
    if tok.startswith('"'):
        return rs_str(tok), "str"
    if re.fullmatch(r"-?\d+", tok):
        return tok, "i64"
    if tok in consts:
        return consts[tok], "ident"
    raise ValueError(f"unhandled token: {tok!r}")


def convert_seasons():
    src = (KT / "SeasonCatalog.kt").read_text()
    entries = []
    for raw_text in extract_calls(src, "SeasonInfo"):
        raw = split_args(raw_text)
        if len(raw) != 7:
            raise ValueError(f"SeasonInfo with {len(raw)} args: {raw[:2]}")
        season = int(raw[0])
        vals = [rs_str(raw[i]) for i in range(1, 6)]
        is_classic = raw[6]
        assert is_classic in ("true", "false")
        entries.append(
            f"    SeasonInfo {{ season: {season}, title: {vals[0]}, chapter: {vals[1]}, "
            f"slogan: {vals[2]}, dates: {vals[3]}, description: {vals[4]}, is_classic: {is_classic} }},"
        )
    body = "\n".join(entries)
    code = f'''//! GENERATED by tools/kotlin_catalogs.py — 1:1 port of Owen-Launcher
//! `app/src/main/kotlin/com/abdallhrgx/owenlauncher/core/{{SeasonCatalog,SeasonInfo}}.kt`.
//! Do not edit by hand; re-run the generator instead.
#![allow(clippy::redundant_static_lifetimes)]

/// Port of `SeasonInfo.kt` (data class).
pub struct SeasonInfo {{
    pub season: u32,
    pub title: &'static str,
    pub chapter: &'static str,
    pub slogan: &'static str,
    pub dates: &'static str,
    pub description: &'static str,
    pub is_classic: bool,
}}

/// Port of `SeasonCatalog.kt` (object) — the entries list.
pub const ENTRIES: &[SeasonInfo] = &[
{body}
];

fn by_season_num() -> std::collections::BTreeMap<u32, &'static SeasonInfo> {{
    ENTRIES.iter().map(|e| (e.season, e)).collect()
}}

/// `SeasonCatalog.get(season)`
pub fn get(season: u32) -> Option<&'static SeasonInfo> {{
    by_season_num().get(&season).copied()
}}

/// `SeasonCatalog.all()`
pub fn all() -> Vec<&'static SeasonInfo> {{
    ENTRIES.iter().collect()
}}

/// `SeasonCatalog.title(season)`
pub fn title(season: u32) -> String {{
    if season == 10 {{
        return "Season X".to_string();
    }}
    match get(season) {{
        Some(_) => format!("Season {{season}}"),
        None => format!("Season {{season}}"),
    }}
}}

/// `SeasonCatalog.versionPrefix(version)`
pub fn version_prefix(version: &str) -> String {{
    version.split('.').next().unwrap_or(version).to_string()
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn has_28_entries_without_season_11() {{
        assert_eq!(ENTRIES.len(), 28);
        assert!(get(11).is_none(), "season 11 never existed");
        assert!(get(5).is_some() && get(33).is_some());
    }}

    #[test]
    fn title_season_x_special_case() {{
        assert_eq!(title(10), "Season X");
        assert_eq!(title(5), "Season 5");
        assert_eq!(title(999), "Season 999");
    }}
}}
'''
    (OUT / "season_catalog.rs").write_text(code)
    return len(entries)


def convert_versions():
    src = (KT / "VersionCatalog.kt").read_text()
    consts = {
        "DEV_APK_URL": None,  # replaced below by the literal from the same file
        "DEV_PACKAGE": None,
    }
    url_m = re.search(r'const val DEV_APK_URL = "([^"]+)"', src)
    pkg_m = re.search(r'const val DEV_PACKAGE = "([^"]+)"', src)
    assert url_m and pkg_m
    consts["DEV_APK_URL"] = rs_str(f'"{url_m.group(1)}"')
    consts["DEV_PACKAGE"] = rs_str(f'"{pkg_m.group(1)}"')

    entries = []
    for raw_text in extract_calls(src, "OgVersion"):
        if "val " in raw_text:
            continue  # the `data class OgVersion(...)` declaration itself
        raw = split_args(raw_text)
        if len(raw) not in (7, 9):
            raise ValueError(f"OgVersion with {len(raw)} args: {raw[:3]}")
        season, version = int(raw[0]), rs_str(raw[1])
        cl = raw[2].rstrip("L")
        release_key = rs_str(raw[3])
        manifest_hash, mh = rs_scalar(raw[4], consts)
        if mh == "opt":
            manifest_hash = "None"
        uptodown_id, uid = rs_scalar(raw[5], consts)
        if uid == "opt":
            uptodown_id = "None"
        if len(raw) == 7:
            is_dev = raw[6]
            assert is_dev in ("true", "false"), f"bad is_dev: {raw}"
            direct = "String::new()"
            fixed = "String::new()"
        else:
            is_dev = raw[6]
            direct, d = rs_scalar(raw[7], consts)
            if d != "ident":
                raise ValueError(f"unexpected direct arg {raw[7]!r} in entry: {raw}")
            fixed, f = rs_scalar(raw[8], consts)
            if f != "ident":
                raise ValueError(f"unexpected fixed arg {raw[8]!r} in entry: {raw}")
        assert is_dev in ("true", "false")
        entries.append(
            f"    OgVersion {{ season: {season}, version: {version}, cl: {cl}, release_key: {release_key}, "
            f"manifest_hash: {manifest_hash}, uptodown_id: {uptodown_id}, is_dev: {is_dev}, "
            f"direct_apk_url: {direct}, fixed_package: {fixed} }},"
        )
    body = "\n".join(entries)
    count = len(entries)
    code = f'''//! GENERATED by tools/kotlin_catalogs.py — 1:1 port of Owen-Launcher
//! `app/src/main/kotlin/com/abdallhrgx/owenlauncher/core/VersionCatalog.kt`.
//! Do not edit by hand; re-run the generator instead.

/// `VersionCatalog.DEV_APK_URL`
pub const DEV_APK_URL: &str = {consts['DEV_APK_URL']};
/// `VersionCatalog.DEV_PACKAGE`
pub const DEV_PACKAGE: &str = {consts['DEV_PACKAGE']};

/// Port of `VersionCatalog.OgVersion` (data class).
#[derive(Debug, Clone, PartialEq)]
pub struct OgVersion {{
    pub season: u32,
    pub version: String,
    pub cl: i64,
    pub release_key: String,
    pub manifest_hash: Option<String>,
    pub uptodown_id: Option<i64>,
    pub is_dev: bool,
    pub direct_apk_url: String,
    pub fixed_package: String,
}}

/// `VersionCatalog.all` (private list) — {{count}} entries.
pub const ALL: &[OgVersion] = &[
{body}
];

/// `VersionCatalog.getAll()`
pub fn get_all() -> Vec<&'static OgVersion> {{
    ALL.iter().collect()
}}

/// `VersionCatalog.bySeason(season)` — sorted by CL descending.
pub fn by_season(season: u32) -> Vec<&'static OgVersion> {{
    let mut list: Vec<&OgVersion> = ALL.iter().filter(|v| v.season == season).collect();
    list.sort_by(|a, b| b.cl.cmp(&a.cl));
    list
}}

/// `VersionCatalog.byUptodownId(versionId)`
pub fn by_uptodown_id(version_id: i64) -> Option<&'static OgVersion> {{
    ALL.iter().find(|v| v.uptodown_id == Some(version_id))
}}

/// `VersionCatalog.find(version, cl, dev)`
pub fn find(version: &str, cl: Option<i64>, dev: bool) -> Option<&'static OgVersion> {{
    let trimmed = version.trim();
    let base = trimmed.split('-').next().unwrap_or(trimmed);
    ALL.iter().find(|v| {{
        let v_match = v.version == base || v.version.split('-').next().unwrap_or(&v.version) == base;
        v_match && (cl.is_none() || v.cl == cl.unwrap_or_default()) && v.is_dev == dev
    }})
}}

/// `VersionCatalog.seasons()`
pub fn seasons() -> Vec<u32> {{
    let mut list: Vec<u32> = ALL.iter().map(|v| v.season).collect();
    list.sort();
    list.dedup();
    list
}}

#[cfg(test)]
mod tests {{
    use super::*;

    #[test]
    fn catalog_shape() {{
        assert_eq!(ALL.len(), {count});
        assert_eq!(ALL.len(), 264);
        // the dev build is the last entry, like the Kotlin list
        let dev = ALL.last().unwrap();
        assert!(dev.is_dev);
        assert_eq!(dev.season, 10);
        assert_eq!(dev.version, "10.40");
        assert_eq!(dev.fixed_package, DEV_PACKAGE);
        assert_eq!(dev.direct_apk_url, DEV_APK_URL);
    }}

    #[test]
    fn by_season_sorted_desc() {{
        let s5 = by_season(5);
        assert!(s5.windows(2).all(|w| w[0].cl >= w[1].cl));
        assert!(s5.iter().all(|v| v.season == 5));
    }}

    #[test]
    fn find_and_helpers() {{
        assert_eq!(by_uptodown_id(1768085).map(|v| v.version.as_str()), Some("5.41"));
        assert!(find("5.41", Some(4363240), false).is_some());
        assert!(find("10.40", None, true).is_some());
        let seasons = seasons();
        assert_eq!(seasons.first().copied(), Some(5));
        assert_eq!(seasons.last().copied(), Some(33));
        assert!(!seasons.contains(&11));
    }}
}}
'''
    (OUT / "version_catalog.rs").write_text(code)
    return count


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    n_seasons = convert_seasons()
    n_versions = convert_versions()
    print(f"season entries: {n_seasons}")
    print(f"version entries: {n_versions}")
    if n_seasons != 28:
        sys.exit("expected 28 SeasonInfo entries")
    if n_versions != 264:
        sys.exit("expected 264 OgVersion entries")


if __name__ == "__main__":
    main()
