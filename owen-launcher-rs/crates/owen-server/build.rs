//! build.rs — embed the Owen data tree INTO the library.
//!
//! The user-facing requirement: "لماذا لا تجعل ملفات json تكون محقنة داخل
//! نفس libOwenServer.so نفسه؟" — every JSON/INI the server serves must live
//! inside the compiled `.so`, so a bare `libOwenServer.so` (deployed inside
//! the launcher APK) hosts the full backend with ZERO external files.
//! Files that appear on disk under the data dir still WIN (operators can
//! override), the embedded copies are the built-in fallback.
//!
//! The tree walked is `<workspace>/data/owen` (battlepass, profiles,
//! responses, manifests, CloudStorage INIs). The lawin tree keeps its own
//! deployment path (it ships as APK assets and is copied by the deployer).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let data_root = manifest_dir
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .join("data/owen");

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    if data_root.is_dir() {
        collect(&data_root, &data_root, &mut files);
    }
    files.sort();

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let dest = out_dir.join("embedded_data.rs");

    let mut src = String::new();
    src.push_str("// @generated by owen-server/build.rs — DO NOT EDIT.\n");
    src.push_str("// Every file of data/owen compiled into the binary (the libOwenServer.so\n");
    src.push_str("// self-contained data fallback; disk files under the data dir override).\n\n");
    src.push_str("pub static EMBEDDED_DATA: &[(&str, &[u8])] = &[\n");
    for (rel, path) in &files {
        let escaped = rel.replace('\\', "/");
        src.push_str(&format!(
            "    ({escaped:?}, include_bytes!({:?})),\n",
            path.to_string_lossy()
        ));
    }
    src.push_str("];\n");
    fs::write(&dest, src).expect("write embedded_data.rs");

    println!(
        "cargo:rerun-if-changed={}",
        data_root.display()
    );
    // also rerun when files are added/removed inside the tree
    println!("cargo:rerun-if-changed={}", manifest_dir.join("build.rs").display());
    println!(
        "cargo:warning=owen-server: {} data files embedded into the library",
        files.len()
    );
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.is_file() {
            let rel = path
                .strip_prefix(root)
                .expect("inside root")
                .to_string_lossy()
                .into_owned();
            out.push((rel, path));
        }
    }
}
